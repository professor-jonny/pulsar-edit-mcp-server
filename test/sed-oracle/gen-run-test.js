'use strict';
// test/sed-oracle/gen-run-test.js - writes test/golden/sed-run-cases.js, the recorded expectations used by
// test/sed-run.test.js. Every expected output comes from a REAL GNU sed 4.9 (bytes in, bytes out).
//
//   node test/sed-oracle/gen-run-test.js [outfile]      (needs sed on PATH, see README.md)
//
// Cases: each script of run-diff.js on a few inputs (default output on three inputs, -n on one), the multibyte
// scripts on the non-ASCII inputs, and scope cases (the script run as if wrapped in `from,to{ ... }`).
// Left out on purpose (they differ between the Windows port and Linux sed, so they are covered by hand-written
// Linux-recorded cases in the test): `l` together with a TAB, and characters outside the BMP (emoji).

const fs = require('fs');
const path = require('path');
const { SCRIPTS, INPUTS } = require('./run-diff');
const { runSed, requireSed } = require('./oracle');
const { parseScript } = require('../../lib/sed-parse');

const outFile = process.argv[2] || path.join(__dirname, '..', 'golden', 'sed-run-cases.js');

const EXTRA = ['/a/s//\\1/', 's/\\(a\\)\\|b/\\1/;s//\\2/', '/\\(a\\)/s//\\2/', '/\\(a\\)/s//\\1/', 's/a/b/;s//\\1/', 's/\\(a\\)/\\1/;s//\\3/',
  's/\\(a\\)/\\1/;s//\\1\\1/', '/a/,/b/s//\\1/', '/b/{s//x/;s//\\1/}'];
const SCOPE_SCRIPTS = ['p', 'd', 's/$/!/', 'N;s/\\n/-/', '$!N;P;D', 'n;d', '=', '2q', 'G', 'x;G', '/2/d', '2,3d', '$p', '$d', '1!G;h;$!d',
  'a X', 'y/123/abc/', 'N;N;D', 's/[0-9]/<&>/', '3,$s/$/?/', '0~2d', 'c Z', '$!N;$!D', 'i A', 'l', '2{h;d};${G}'];
const SCOPES = [[2, 3], [1, 1], [4, 9], [3, 3], [1, 5], [2, 2]];

function hasTabAndL(parsed, input) {
  return input.indexOf('\t') >= 0 && parsed.cmds.some((c) => c.cmd === 'l');
}
function nonBmp(s) { return /[\ud800-\udbff]/.test(s); }

function real(script, input, n) {
  const r = runSed((n ? ['-n'] : []).concat(['-e', script]), input);
  const isErr = r.status !== 0 && typeof r.err === 'string' && /sed:/.test(r.err);
  return isErr ? null : { out: r.out, status: r.status };
}

function main() {
  console.log(requireSed());
  const mbStart = SCRIPTS.indexOf('s/x*/-/');
  const asciiIn = [INPUTS[0], INPUTS[3], INPUTS[7]];
  const mbIn = INPUTS.slice(10).filter((s) => !nonBmp(s)).concat([INPUTS[8]]);
  const seen = new Set();
  const cases = [];
  const add = (script, n, input) => {
    const key = JSON.stringify([script, n, input]);
    if (seen.has(key)) return;
    seen.add(key);
    let parsed;
    try { parsed = parseScript(script, { extended: false, sandbox: true }); } catch (e) { return; }
    if (hasTabAndL(parsed, input) || nonBmp(input)) return;
    // a stray byte next to a word assertion: the Windows port differs from Linux (hand-written Linux cases cover it)
    if (/[\udc80-\udcff]/.test(input) && /\\[bB<>]/.test(script)) return;
    const r = real(script, input, n);
    cases.push(r === null ? [script, n ? 1 : 0, input, null, 1] : [script, n ? 1 : 0, input, r.out, r.status]);
  };
  SCRIPTS.concat(EXTRA).forEach((script, idx) => {
    for (const input of asciiIn) add(script, false, input);
    add(script, true, INPUTS[0]);
    if (idx >= mbStart) for (const input of mbIn) add(script, false, input);
  });

  const scopeCases = [];
  for (const script of SCOPE_SCRIPTS) {
    for (const [from, to] of SCOPES) {
      for (const input of [INPUTS[0], INPUTS[3]]) {
        const wrapped = from + ',' + to + '{\n' + script + '\n}';
        const r = real(wrapped, input, false);
        scopeCases.push([script, from, to, input, r === null ? null : r.out, r === null ? 1 : r.status]);
      }
    }
  }

  const lines = [];
  lines.push("'use strict';");
  lines.push('// GENERATED by test/sed-oracle/gen-run-test.js from a real GNU sed 4.9 (bytes in, bytes out). Do not edit by hand.');
  lines.push('// A stray byte that is not valid UTF-8 appears as \\udcXX (the raw byte 0xXX), see encodeBytes in lib/sed-run.js.');
  lines.push('// CASES:       [script, silent (-n) 0/1, input, expected output (null = sed stops with an error), exit status]');
  lines.push('// SCOPE_CASES: [script, from, to, input, expected output of the script wrapped in `from,to{ ... }`, exit status]');
  const asc = (c) => JSON.stringify(c).replace(/[\u007f-\uffff]/g, (ch) => '\\u' + ch.charCodeAt(0).toString(16).padStart(4, '0'));
  lines.push('const CASES = [');
  for (const c of cases) lines.push('  ' + asc(c) + ',');
  lines.push('];');
  lines.push('const SCOPE_CASES = [');
  for (const c of scopeCases) lines.push('  ' + asc(c) + ',');
  lines.push('];');
  lines.push('module.exports = { CASES, SCOPE_CASES };');
  fs.writeFileSync(outFile, lines.join('\n') + '\n');
  console.log('wrote ' + outFile + ': ' + cases.length + ' cases, ' + scopeCases.length + ' scope cases');
}

main();
